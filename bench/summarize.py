"""Leaderboard over every stored benchmark run: scans <results>/{hot3d,egostandard,bench2d,seg}/<run>/metrics*.json and
writes one markdown file (+ CSV per dataset) so all numbers live in one place.

    python -m bench.summarize --results $RESULTS --out $RESULTS/leaderboard.md
"""
import argparse
import csv
import glob
import json
import os

HOT3D = ["det_recall", "det_precision", "handedness_acc", "pa_mpjpe", "pa_mpjpe_p", "pa_mpjpe_v", "pa_mpvpe", "pa_mpvpe_p", "f5",
         "f15", "rr_mpjpe", "rr_mpjpe_p", "root_err", "mrrpe", "accel_err", "jitter", "latency_ms_median"]
SUBSETS = ["all", "hot3d", "cmu", "coco", "hint_nd", "hint_epick"]
SEG = ["miou", "miou_matched", "recall50", "precision50", "boundary_f", "handedness_acc", "latency_ms_median"]


def fmt(v):
    return f"{v:.3f}" if isinstance(v, float) else ("" if v is None else str(v))


def table(rows, cols):
    out = ["| run | " + " | ".join(cols) + " |", "|---" * (len(cols) + 1) + "|"]
    out += ["| " + " | ".join([r["run"]] + [fmt(r.get(c)) for c in cols]) + " |" for r in rows]
    return out


def main(args):
    md, R = [f"# Benchmark leaderboard (auto-generated by bench/summarize.py from {args.results})", ""], args.results
    rows = []
    for f in sorted(glob.glob(os.path.join(R, "hot3d", "*", "metrics.json"))):
        m = json.load(open(f))
        rows.append(dict(run=os.path.basename(os.path.dirname(f)), **{k: m.get(k) for k in HOT3D}))
    rows.sort(key=lambda r: r.get("pa_mpjpe") or 1e9)
    md += ["## HOT3D v1 (3D, mm; sorted by PA-MPJPE)", ""] + table(rows, HOT3D) + [""]
    sets = {"hot3d": rows}
    rows = []
    for f in sorted(glob.glob(os.path.join(R, "egostandard", "*", "metrics.json"))):
        m = json.load(open(f))
        rows.append(dict(run=os.path.basename(os.path.dirname(f)), **{k: m.get(k) for k in HOT3D}))
    rows.sort(key=lambda r: r.get("rr_mpjpe_p") or 1e9)
    if rows:
        md += ["## EgoStandard (3D, mm; held out of training; sorted by rr-MPJPE-p)", ""] + table(rows, HOT3D) + [""]
        sets["egostandard"] = rows
    rows = []
    for f in sorted(glob.glob(os.path.join(R, "bench2d", "*", "metrics2d*.json"))):
        m = json.load(open(f))
        key = os.path.basename(f)[len("metrics2d"):-len(".json")].lstrip("_") or "joints2d"
        r = dict(run=os.path.basename(os.path.dirname(f)) + ("" if key == "joints2d" else f" [{key}]"))
        for s in SUBSETS:
            r[f"pck10/{s}"] = m.get(s, {}).get("pck10")
        a = m.get("all", {})
        r.update(recall=a.get("recall"), precision=a.get("precision"), auc=a.get("auc"), pck10_all=a.get("pck10_all"),
                 auc_all=a.get("auc_all"), latency=a.get("latency_ms_median"))
        rows.append(r)
    rows.sort(key=lambda r: -(r.get("pck10_all") or 0))
    cols = [f"pck10/{s}" for s in SUBSETS] + ["recall", "precision", "auc", "pck10_all", "auc_all", "latency"]
    md += ["## bench2d (PCK@0.1 on matched hands per subset; *_all counts misses; sorted by pck10_all)", ""] + table(rows, cols) + [""]
    sets["bench2d"] = rows
    rows = []
    for f in sorted(glob.glob(os.path.join(R, "seg", "*", "metrics_seg*.json"))):
        m = json.load(open(f))
        m = m.get("overall", m)
        key = os.path.basename(f)[len("metrics_seg"):-len(".json")].lstrip("_") or "mask"
        rows.append(dict(run=os.path.basename(os.path.dirname(f)) + f" [{key}]", **{k: m.get(k) for k in SEG}))
    rows.sort(key=lambda r: -(r.get("miou") or 0))
    md += ["## Segmentation (VISOR val, hand+arm GT; sorted by mIoU)", ""] + table(rows, SEG) + [""]
    sets["seg"] = rows
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    open(args.out, "w").write("\n".join(md))
    for name, rs in sets.items():
        if rs:
            with open(os.path.splitext(args.out)[0] + f"_{name}.csv", "w", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=list(rs[0]))
                w.writeheader()
                w.writerows(rs)
    print("wrote", args.out, {k: len(v) for k, v in sets.items()})


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", required=True)
    p.add_argument("--out", required=True)
    main(p.parse_args())
